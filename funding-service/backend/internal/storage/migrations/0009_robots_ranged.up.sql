-- Диапазонные роботы в истории.
--
-- До сих пор робот опознавался по повторяющейся лотовке, и находка означала
-- «принт такого-то размера через такой-то такт». Роботы, которые держат ровным
-- только такт, а объём каждый раз меняют, ищутся отдельным проходом по всей
-- стороне, и границы лотовки у них значат совсем другое: не допуск склейки, а
-- размах, в котором робот гуляет.
--
-- Без этого признака история сваливала оба вида в один столбец, и строку
-- «12–300 л» нельзя было отличить от склеенной ошибки разбора.
ALTER TABLE robots ADD COLUMN IF NOT EXISTS ranged BOOLEAN NOT NULL DEFAULT FALSE;

package robots

import "time"

// Склейка сделок в принты рыночного приказа.
//
// Биржа печатает не приказы, а сделки: рыночный приказ на 372 лота съедает
// несколько лимиток и выходит в ленту пятью строчками — 50, 100, 125, 56, 41.
// Робот при этом отправил один приказ одного размера, и именно этот размер
// повторяется с его тактом.
//
// Пока детектор работал по сырым сделкам, на ликвидной бумаге он не видел
// ничего: лотовка робота рассыпалась на куски разной величины, и периодичности
// в них не было. Замер на дневной ленте ISS: по GAZP в окне 17:05–17:35 сделок
// размера 371–373 лота всего пять, а склеенных приказов — 52, и двадцать один
// интервал между ними ровно по тридцать секунд. То же по PLZL (413–414 лотов,
// 31 интервал по 30 с) и по T (2741 лот, интервалы по 60 с).
//
// Склейка — это ещё и вопрос честности цифр на странице: «объём за раз» без неё
// показывал кусок приказа, а не приказ.

// DefaultAggressorGap — на сколько могут разъехаться во времени соседние сделки
// одного приказа.
//
// Значение выбрано так, чтобы работать с обоими источниками сразу. Публичный фид
// ISS округляет время сделки до секунды: там сделки одного приказа приходят с
// одинаковой меткой (разница 0), а соседняя секунда уже за порогом. Поток брокера
// отдаёт миллисекунды, и разбор одного приказа по стакану укладывается в десятки
// миллисекунд.
const DefaultAggressorGap = 200 * time.Millisecond

// DefaultAggressorSpan — предел длины одной склейки.
//
// Нужен только для потока с миллисекундной меткой: на плотной ленте сделки разных
// участников идут сплошняком, и без предела цепочка склеивалась бы бесконечно.
// На секундной метке ISS предел не срабатывает: там склеивается ровно одна секунда.
const DefaultAggressorSpan = 2 * time.Second

// mergeAggressors склеивает подряд идущие сделки одной стороны в принты приказов.
//
// Лента должна быть отсортирована по времени (Detector.Add это гарантирует).
// Размеры складываются, цена берётся последняя — приказ «доехал» именно до неё,
// время остаётся временем первой сделки: с него робот начал такт.
func mergeAggressors(tape []Print, gap, span time.Duration) []Print {
	if len(tape) < 2 {
		return tape
	}
	out := make([]Print, 0, len(tape))
	cur := tape[0]
	cur.Trades = 1
	last := cur.Time
	for _, p := range tape[1:] {
		joins := p.Side == cur.Side &&
			p.Time.Sub(last) <= gap &&
			!p.Time.Before(last) &&
			p.Time.Sub(cur.Time) <= span
		if joins {
			cur.Qty += p.Qty
			cur.Price = p.Price
			cur.Trades++
			last = p.Time
			continue
		}
		out = append(out, cur)
		cur = p
		cur.Trades = 1
		last = p.Time
	}
	return append(out, cur)
}

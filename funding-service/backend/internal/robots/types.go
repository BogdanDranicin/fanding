// Package robots ищет в ленте сделок MOEX торговых роботов: повторяющиеся
// принты одного размера, идущие через равные промежутки времени.
//
// Робот описывается четырьмя наблюдаемыми величинами — тикер, направление
// (агрессор покупал или продавал), лотовка (размер принта) и тайминг (период
// повторения). Пример: по SBER каждые 11.2 с проходит покупка 3011–3013 лотов.
package robots

import (
	"math"
	"time"
)

// Side — направление агрессора в сделке (колонка BUYSELL в ленте ISS).
// Лента показывает сторону инициатора: B — робот берёт по оферу (лонг),
// S — робот льёт по биду (шорт).
type Side string

const (
	SideBuy  Side = "B"
	SideSell Side = "S"
)

// Print — одна сделка из ленты биржи.
type Print struct {
	TradeNo int64
	Symbol  string
	// Time — биржевое время сделки (TRADEDATE+TRADETIME), не момент получения:
	// публичный фид ISS запаздывает на минуты, и по времени прихода периодичность
	// восстановить нельзя. Разрешение биржевой метки — одна секунда.
	Time  time.Time
	Price float64
	Qty   float64 // объём сделки в лотах
	Side  Side
	// Trades — сколько сделок биржи склеилось в этот принт. Ноль у сырой сделки,
	// 1 и больше — у принта, собранного mergeAggressors из приказа.
	Trades int
}

// Robot — обнаруженная закономерность в ленте одного тикера.
type Robot struct {
	Symbol string `json:"symbol"`
	Side   Side   `json:"side"`

	// Лотовка: диапазон размеров принтов, попавших в кластер, и типичный размер.
	QtyMin     float64 `json:"qty_min"`
	QtyMax     float64 `json:"qty_max"`
	QtyTypical float64 `json:"qty_typical"`

	// Тайминг: период повторения в секундах и разброс интервалов вокруг него
	// (коэффициент вариации; у настоящего робота он околонулевой).
	PeriodSec float64 `json:"period_sec"`
	Jitter    float64 `json:"jitter"`

	Prints int `json:"prints"` // сколько принтов в кластере
	Beats  int `json:"beats"`  // сколько тактов периода уложилось в серию
	// Hits — сколько тактов серии реально заняты принтами. Отношение Hits к Beats —
	// занятость сетки: у настоящего робота она близка к единице, а у сетки, натянутой
	// на случайные сделки, или у неверно выбранной кратности такта — около половины.
	Hits       int     `json:"hits"`
	Confidence float64 `json:"confidence"` // 0..1, насколько уверенно это робот

	// Provisional — серия ещё короче той, на которой периодичность отличима от
	// случайного совпадения (см. ConfidentPrints). Такой робот показывается сразу,
	// как просили, но помечен: подтвердит он себя или отвалится по пропущенному
	// такту, станет ясно за следующие один-два такта.
	Provisional bool `json:"provisional"`

	FirstSeen time.Time `json:"first_seen"`
	LastSeen  time.Time `json:"last_seen"`

	PriceFirst float64 `json:"price_first"`
	PriceLast  float64 `json:"price_last"`

	// PrintTrades — из скольких сделок биржи в среднем собран один принт робота.
	// Единица означает, что приказ забирал одну лимитку целиком; пять — что робот
	// каждый такт сметает пять заявок. Показывается на странице, чтобы «объём за
	// раз» читался как приказ, а не как строчка ленты.
	PrintTrades float64 `json:"print_trades"`
}

// ConfidentPrints — длина серии, начиная с которой периодичность уже не объясняется
// случайным совпадением размеров. Ниже неё робот считается предварительным.
const ConfidentPrints = 6

// Volume — суммарный объём серии в лотах: сколько робот уже напечатал.
func (r Robot) Volume() float64 { return r.QtyTypical * float64(r.Prints) }

// NextBeatAfter — когда робот ударит в следующий раз после момента t.
//
// Считается продолжением фазы серии вперёд, а не «последний принт плюс период»:
// публичная лента ISS запаздывает на минуты, и к моменту вопроса робот успевает
// отработать несколько тактов, которых мы ещё не видели. Период известен с
// точностью до сотых долей секунды, поэтому фаза переносится вперёд без накопления
// заметной ошибки.
func (r Robot) NextBeatAfter(t time.Time) time.Time {
	if r.PeriodSec <= 0 || r.LastSeen.IsZero() {
		return time.Time{}
	}
	period := time.Duration(r.PeriodSec * float64(time.Second))
	if period <= 0 {
		return time.Time{}
	}
	elapsed := t.Sub(r.LastSeen)
	beats := math.Floor(float64(elapsed)/float64(period)) + 1
	if beats < 1 {
		beats = 1
	}
	return r.LastSeen.Add(time.Duration(beats * float64(period)))
}

// Config — пороги детектора. Значения по умолчанию даёт DefaultConfig.
type Config struct {
	// Window — сколько последней ленты анализируем.
	Window time.Duration

	// MinPrints/MinBeats — минимум принтов в серии и минимум тактов, которые она
	// должна накрыть. Это пороги для акций и фьючерсов.
	//
	// Три принта — это два интервала: минимум, на котором у периода вообще есть
	// чем себя подтвердить, и самый ранний момент, когда робота можно показать.
	// Цену такой скорости платит точность: на трёх принтах периодичность ещё
	// объяснима совпадением, и находка держится только проверкой на неслучайность
	// в fitGrid и правилом «на короткой серии такт пропускать нельзя». Всё, что
	// короче ConfidentPrints, помечается Provisional, а окончательный отсев ложных
	// ложится на правило пропущенных тактов в реестре сессий: серия, которой не
	// было, замолкает на следующем же такте.
	MinPrints int
	MinBeats  int

	// MinPrintsCurrency/MinBeatsCurrency — пороги для валютных инструментов: там
	// ликвидность собрана в нескольких контрактах, и лишний такт ожидания стоит
	// дороже, чем лишняя проверка.
	//
	// Два принта — это один интервал, и проверять период нечем, кроме попадания в
	// границы: подтверждения периодичности на такой серии нет в принципе, и всё,
	// что она сообщает, — «два приказа одного размера прошли через столько-то
	// секунд». Такая находка живёт до второго такта: не подтвердилась — снята.
	MinPrintsCurrency int
	MinBeatsCurrency  int

	// QtyTolRel/QtyTolAbs — допуск на «одинаковый размер»: робот дробит заявку и
	// печатает не строго одну и ту же лотовку. Допуск абсолютный, ±1 лот:
	// относительный на крупной лотовке (±1% от 3000 — это ±30 лотов) склеивал
	// в одного робота заведомо разные серии.
	QtyTolRel float64
	QtyTolAbs float64

	// MinPeriod/MaxPeriod — границы правдоподобного тайминга. Нижняя граница не
	// может быть меньше пары секунд: биржевая метка времени дискретна по секунде.
	MinPeriod time.Duration
	MaxPeriod time.Duration

	// PeriodTolAbs/PeriodTolRel — допуск на отклонение принта от сетки такта.
	//
	// Абсолютная часть — это разброс самого робота: свои приказы он шлёт по своим
	// часам, и десятки миллисекунды набегают на очереди биржи. К ней прибавляется
	// половина шага метки времени источника (см. thresholds.grain): публичный фид
	// ISS округляет время до секунды, и там к разбросу робота добавляется чужое
	// округление. Относительная часть намеренно мала: на длинном периоде щедрый
	// допуск позволяет подогнать «период» под любые случайные сделки, и лента
	// начинает кишеть несуществующими роботами.
	PeriodTolAbs time.Duration
	PeriodTolRel float64

	// MaxSkip — сколько тактов подряд робот может промолчать (не нашёл ликвидности),
	// чтобы серия всё ещё считалась непрерывной.
	MaxSkip int

	// MinOccupancy — какая доля тактов серии обязана быть занята принтами. Робот
	// изредка пропускает такт, не найдя ликвидности, но серия, где занят каждый
	// третий такт, — это уже не робот, а сетка, натянутая на случайные сделки.
	MinOccupancy float64

	// MaxJitter — максимальный разброс принтов вокруг сетки такта, в долях периода.
	// Главный фильтр против случайного потока: у пуассоновской ленты разброс
	// сравним с самим периодом, у робота близок к нулю.
	//
	// Это база, к которой добавляется разброс от округления времени в источнике
	// (см. maxJitterFor): у публичного фида ISS с его секундной меткой робот с
	// коротким тактом «дрожит» на пустом месте, а у потока брокера — нет.
	MaxJitter float64

	// NoiseSigma — во сколько стандартных отклонений находка обязана превысить
	// случайный фон. Каждый такт ловит принты в окно допуска, и на плотной ленте
	// в него попадают чужие сделки сами собой; серия принимается, только если
	// попаданий заметно больше, чем даёт эта плотность (см. fitGrid).
	NoiseSigma float64

	// AggressorGap/AggressorSpan — параметры склейки сделок в принты приказов
	// (см. aggressor.go). Нули означают работу по сырым сделкам.
	AggressorGap  time.Duration
	AggressorSpan time.Duration
}

// DefaultConfig — пороги, подобранные под ленту MOEX с секундной меткой времени.
func DefaultConfig() Config {
	return Config{
		Window:            30 * time.Minute,
		MinPrints:         3,
		MinBeats:          2,
		MinPrintsCurrency: 2,
		MinBeatsCurrency:  1,
		QtyTolRel:         0,
		QtyTolAbs:         1,
		MinPeriod:         2 * time.Second,
		MaxPeriod:         5 * time.Minute,
		PeriodTolAbs:      250 * time.Millisecond,
		PeriodTolRel:      0.005,
		MaxSkip:           3,
		MaxJitter:         0.05,
		MinOccupancy:      0.6,
		NoiseSigma:        3,
		AggressorGap:      DefaultAggressorGap,
		AggressorSpan:     DefaultAggressorSpan,
	}
}

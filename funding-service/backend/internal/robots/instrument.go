package robots

// Instrument — справочные данные инструмента: то, что на странице стоит рядом с
// тикером и не выводится из ленты сделок.
//
// Без них страница показывала голый код: «AFLT», «CRU6». По коду не видно ни что
// это за бумага, ни во сколько раз лот больше самой бумаги, ни насколько мелким
// шагом она ходит, — а без шага цены нельзя прочесть и графу «ход цены»: полпроцента
// на бумаге с шагом 0.0005 и на бумаге с шагом 1 рубль — это разное число тиков.
type Instrument struct {
	Symbol string `json:"symbol"`
	// Name — человеческое имя: «Аэрофлот», «Si-9.26».
	Name string `json:"name"`
	// LotSize — сколько бумаг в одном лоте. Лотовка робота считается в лотах, и
	// без этого числа её не перевести в бумаги.
	LotSize int `json:"lot_size"`
	// MinStep — шаг цены инструмента.
	MinStep float64 `json:"min_step"`
	// Decimals — сколько знаков после запятой держит биржевая цена.
	Decimals int `json:"decimals"`
}

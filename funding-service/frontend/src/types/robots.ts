// Робот, найденный в ленте сделок: серия одинаковых принтов с ровным периодом.
export interface RobotSession {
  id: number;
  symbol: string;
  /** Сторона агрессора: B — покупал (лонг), S — продавал (шорт). */
  side: 'B' | 'S';
  /** Лотовка: границы размеров принтов и типичный размер. */
  qty_min: number;
  qty_max: number;
  qty_typical: number;
  /** Тайминг: период повторения в секундах. */
  period_sec: number;
  /** Разброс интервалов вокруг периода; у настоящего робота близок к нулю. */
  jitter: number;
  prints: number;
  beats: number;
  confidence: number;
  /** Серия ещё короче той, на которой периодичность отличима от совпадения. */
  provisional: boolean;
  first_seen: string;
  last_seen: string;
  price_first: number;
  price_last: number;
  detected_at: string;
  updated_at: string;
  /** Робот печатает прямо сейчас. */
  active: boolean;
  /** Сколько тактов подряд робот промолчал: 1 — подсветка, 2 — робота снимают. */
  misses: number;
  /**
   * Когда ждать следующий принт. Считается продолжением фазы вперёд по стенным
   * часам: лента ISS запаздывает на минуты, и «последний принт плюс период»
   * указывал бы в прошлое.
   */
  next_beat_at: string;
  /** Объём робота за раз: сколько лотов проходит один его принт. */
  print_lots: number;
  /** Сколько робот напечатал за всю серию, лотов. */
  volume_lots: number;
  /** Дневной оборот инструмента на стороне робота — для справки. */
  day_side_lots: number;
  /** Оборот инструмента за час перед последним принтом — знаменатель силы. */
  hour_lots: number;
  /** В скольких минутах окна вообще были сделки. */
  hour_minutes: number;
  /** Границы часового окна, МСК. */
  hour_from: string;
  hour_to: string;
  /** Непустое — сбор начался внутри окна, час набран не целиком, сила завышена. */
  hour_since: string;
  /** Сила: один принт робота в доле часового оборота бумаги, проценты. */
  strength_pct: number;
}

/** Дневной оборот инструмента, разложенный по стороне агрессора. */
export interface DayVolume {
  symbol: string;
  /** Биржевой день, YYYY-MM-DD MSK. */
  date: string;
  buy: number;
  sell: number;
  trades: number;
  /** Время первой учтённой сделки: после перезапуска среди дня база неполная. */
  since: string;
  latest: string;
}

/** Чем сейчас живёт лента принтов: поток брокера или публичный фид биржи. */
export interface StreamStatus {
  /** Быстрый источник настроен (у сервиса есть токен брокера). */
  enabled: boolean;
  /** Соединение с ним держится прямо сейчас. */
  connected: boolean;
  /** Сколько инструментов покрыто потоком; остальные идут по ISS. */
  symbols: number;
  /** Биржевое время последнего принта из потока. */
  last_print_at?: string;
  /** Замеренное отставание потока от биржи, миллисекунды. 0 — ещё не мерили. */
  lag_ms: number;
  /**
   * Инструменты, которых нет в каталоге брокера: только их лента и остаётся
   * пятнадцатиминутной. Пусто — потоком покрыто всё наблюдение.
   */
  missing?: string[];
}

export interface RobotsResponse {
  /** Инструменты, по которым сейчас идёт лента. */
  watching: string[];
  /** Ленты рынков, которые опрашиваются целиком. */
  tapes: string[];
  /** Чем сужен отбор инструментов внутри лент. */
  watch_rule: string;
  robots: RobotSession[];
  day_volumes: DayVolume[];
  /** Состояние быстрого источника — от него зависит свежесть всей страницы. */
  stream: StreamStatus;
  as_of: string;
}
